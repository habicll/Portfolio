import { Injectable, signal, computed } from '@angular/core';

export type Lang = 'en' | 'fr';

@Injectable({ providedIn: 'root' })
export class TranslationService {
  lang = signal<Lang>('en');

  toggleLang() {
    this.lang.set(this.lang() === 'en' ? 'fr' : 'en');
  }

  t = computed(() => {
    return this.lang() === 'en' ? EN : FR;
  });
}

